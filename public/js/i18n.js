export function normalizeLanguage(language) {
  return /^en(?:[-_]|$)/i.test(String(language ?? '')) ? 'en' : 'zh';
}

/** Translations are plain text. Insert them with textContent, not innerHTML. */
export function t(key, params = {}, language = 'zh') {
  const lang = normalizeLanguage(language);
  const template = MESSAGES[lang][key] ?? MESSAGES.zh[key] ?? String(key);
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params ?? {}, name) ? String(params[name]) : match);
}

export function createTranslator(language) {
  const lang = normalizeLanguage(language);
  return (key, params = {}) => t(key, params, lang);
}

/**
 * Apply optional English names without changing completion or projection data.
 * Always start from the Chinese base catalog when switching languages. Original
 * names remain available as nameZh/labelZh for bilingual search and disclosure.
 * Missing translations retain their original text rather than inventing names.
 */
export function localizeCatalog(catalog, overlay, language = 'zh') {
  if (!catalog || normalizeLanguage(language) !== 'en' || !overlay || overlay.language !== 'en') return catalog;
  const lookup = (table, key) => {
    const value = table?.[key];
    return typeof value === 'string' && value.trim() ? value : undefined;
  };
  const itemNames = new Map(Object.entries(overlay.items ?? {}).map(([id, name]) => [id.toLowerCase(), name]));
  const named = (entry, table) => ({
    ...entry,
    nameZh: entry.nameZh ?? entry.name,
    name: lookup(table, entry.id) ?? entry.name,
  });
  return {
    ...catalog,
    maps: (catalog.maps ?? []).map(entry => named(entry, overlay.maps)),
    categories: (catalog.categories ?? []).map(entry => named(entry, overlay.categories)),
    bells: (catalog.bells ?? []).map(entry => named(entry, overlay.bells)),
    records: (catalog.records ?? []).map(entry => ({
      ...named(entry, overlay.records),
      requirements: (entry.requirements ?? []).map(requirement => ({
        ...requirement,
        labelZh: requirement.labelZh ?? requirement.label,
        label: requirement.type === 'item'
          ? itemNames.get(String(requirement.id ?? '').toLowerCase()) ?? requirement.label
          : requirement.label,
      })),
    })),
    questMetadata: (catalog.questMetadata ?? []).map(quest => {
      const translated = overlay.questMetadata?.[quest.id];
      return {
        ...quest,
        nameZh: quest.nameZh ?? quest.name,
        name: lookup(translated, 'name') ?? quest.name,
        branches: (quest.branches ?? []).map(branch => ({
          ...branch,
          labelZh: branch.labelZh ?? branch.label,
          label: lookup(translated?.branches, branch.id) ?? branch.label,
        })),
      };
    }),
    limitationsZh: catalog.limitationsZh ?? catalog.limitations,
    limitations: Array.isArray(overlay.limitations) ? [...overlay.limitations] : catalog.limitations,
  };
}
